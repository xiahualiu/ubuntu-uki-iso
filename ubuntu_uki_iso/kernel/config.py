"""
Kernel configuration overrides applied to x86_64_defconfig.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class TristateValue(StrEnum):
    """
    Values for boolean and tristate kernel settings.
    """

    Y = "y"
    M = "m"
    N = "n"


@dataclass(frozen=True)
class ConfigEntry:
    """
    One kernel configuration symbol and its override value.
    """

    symbol: str
    value: TristateValue | str

    def render(self) -> str:
        """
        Render this entry in kernel configuration syntax.
        """
        if self.value is TristateValue.N:
            return f"# {self.symbol} is not set\n"
        return f"{self.symbol}={self.value}\n"


